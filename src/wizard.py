"""Setup wizard for openapi: asks for each key (hidden, Enter skips), shows the signup link, stores nothing in the repo.

Kept apart from openapi.py so the router stays small. openapi.py passes in what the wizard needs, so there is no circular import.
Every key is optional: skip anything you do not want and that provider/integration simply stays off.
"""
from __future__ import annotations

import getpass
from typing import Callable

# integrations: (env var, what it is, where to get it)
EXTRAS = (
    ("OBSIDIAN_VAULT", "Obsidian: path to your vault folder (not a secret)", "folder with your .md notes, e.g. ~/Documents/Vault"),
    ("NOTION_API_KEY", "Notion: internal integration token", "https://www.notion.so/profile/integrations (then share pages with it)"),
    ("CODERABBIT_API_KEY", "CodeRabbit: org API key (admin/metrics API, not an LLM)", "https://docs.coderabbit.ai/api"),
    ("CLOUDFLARE_ACCOUNT_ID", "Cloudflare Workers AI account id", "https://dash.cloudflare.com (right sidebar)"),
)


def ask(env: str, hint: str, link: str, have: Callable[[str], bool], store: Callable[[str, str], None], echo: Callable[[str], None], hidden: bool = True) -> None:
    if have(env):
        echo(f"{env}: already set")
        return
    echo(f"\n{hint}\n  {link}")
    val = (getpass.getpass if hidden else input)(f"  {env} (Enter = skip): ").strip()
    if val:
        store(env, val)


def run(providers, have: Callable[[str], bool], store: Callable[[str, str], None], echo: Callable[[str], None] = print, only: str = "") -> None:
    """providers: objects with .name .env .signup. only: restrict to names containing this text."""
    seen: set[str] = set()
    for p in providers:
        if not p.env or p.env in seen or (only and only not in p.name):
            continue
        seen.add(p.env)
        ask(p.env, p.name, p.signup, have, store, echo)
    if not only:
        for env, hint, link in EXTRAS:
            ask(env, hint, link, have, store, echo, hidden=env != "OBSIDIAN_VAULT")


# section order of keys.env.example: the first tag a provider carries from this list decides where it goes
SECTIONS = (
    ("keyless", "no key needed, always on"),
    ("local", "local servers (no key)"),
    ("free", "free tier with a key"),
    ("free-credits", "trial credit"),
    ("search", "search"),
    ("media", "media"),
    ("native-api", "own API, not OpenAI-style"),
    ("gateway", "gateways and routers"),
    ("regional", "regional clouds"),
    ("credits-or-paid", "credits or paid"),
    ("paid", "paid"),
)


def keys_example(providers, tags: dict[str, list[str]]) -> str:
    """The text of keys.env.example: one line per key, grouped, comment = provider and where to get the key. providers: .name .env .signup;
    tags: provider name -> its catalog tags. A provider without a key variable goes under 'no key'; sections keep the order of SECTIONS."""
    groups: dict[str, list[tuple[str, str, str]]] = {t: [] for t, _ in SECTIONS}
    groups["other"] = []
    seen: set[str] = set()
    order = [t for t, _ in SECTIONS] + ["other"]

    def where(p) -> str:
        mine = tags.get(p.name, [])
        return "keyless" if not p.env else next((t for t, _ in SECTIONS if t in mine), "other")

    for p in sorted(providers, key=lambda p: (order.index(where(p)), p.name)):    # a variable shared by several providers goes under the best section
        if p.env and p.env in seen:
            continue
        seen.add(p.env)
        groups[where(p)].append((p.env, p.name, p.signup))
    out = ["# openapi keys: copy to ~/.config/openapi/keys.env and chmod 600.",
           "# Fill only what you want; an empty value = provider off. One line per key: VARIABLE=   # provider: where to get it.",
           "# Generated by `openapi keys-example`; do not edit by hand, edit the catalog or the provider tuple.", ""]
    width = max((len(e) for g in groups.values() for e, _, _ in g), default=0) + 2
    for tag, title in (*SECTIONS, ("other", "other")):
        rows = groups[tag]
        if not rows:
            continue
        out.append(f"# ---- {title} ({len(rows)}) ----")
        for env, name, link in rows:
            out.append((f"{env}=".ljust(width) + f"# {name}: {link}").rstrip() if env else f"# {name}: {link}")
        out.append("")
    out.append("# ---- notes, code and other integrations ----")
    for env, hint, link in EXTRAS:
        out.append(f"{env}=".ljust(width) + f"# {hint}: {link}")
    out.append("TYPESAFE_API_KEY=".ljust(width) + "# Jev (TypeSafe System One): https://console.typesafe.ai/keys")
    return "\n".join(out) + "\n"
